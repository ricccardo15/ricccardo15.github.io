export async function icons(out) {
  const c = canvas(16 * STOPS.length, 16);
  STOPS.forEach((stop, i) => {
    c.map(i * 16, 0, ICONS[stop.id], KEY);
    c.outline('navyDark', { x: i * 16, y: 0, w: 16, h: 16 });
  });
  await c.png(out('icons.png'));
}
